#!/usr/bin/env python3
"""Verify the current Room schema snapshot and sequential migration declarations.

This check is intentionally source-only: it never fabricates a Room JSON snapshot.
A missing current snapshot is a real verification failure and must be generated by
Room/KSP in a connected build environment.
"""
from pathlib import Path
import json, re, sys

root = Path(__file__).resolve().parents[1]
db = root / 'core/android/src/main/kotlin/com/anvex/core/android/db/Database.kt'
text = db.read_text(encoding='utf-8')

m = re.search(r'@Database\([\s\S]*?version\s*=\s*(\d+)', text)
if not m:
    print('FAIL | Could not determine Room database version', file=sys.stderr)
    sys.exit(2)
version = int(m.group(1))
schema = root / 'core/android/schemas/com.anvex.core.android.db.AnvexDatabase' / f'{version}.json'

migration_pairs = {(int(a), int(b)) for a, b in re.findall(r'MIGRATION_(\d+)_(\d+)\b', text)}
missing = [(v, v + 1) for v in range(1, version) if (v, v + 1) not in migration_pairs]
if missing:
    print(f'FAIL | Missing sequential migration declarations: {missing}', file=sys.stderr)
    sys.exit(1)
print(f'PASS | Migration declarations complete: 1->{version}')

if not schema.is_file():
    print(f'FAIL | MISSING current Room schema snapshot: {schema}', file=sys.stderr)
    print('INFO | Generate it with a successful connected Gradle/KSP build; do not hand-author the JSON.', file=sys.stderr)
    print('RESULT: BLOCKED (schema snapshot missing)')
    sys.exit(1)

try:
    data = json.loads(schema.read_text(encoding='utf-8'))
except Exception as exc:
    print(f'FAIL | Invalid Room schema JSON: {exc}', file=sys.stderr)
    sys.exit(1)

actual = data.get('database', {}).get('version')
if actual != version:
    print(f'FAIL | Room schema version mismatch: expected {version}, found {actual}', file=sys.stderr)
    sys.exit(1)

print(f'PASS | Current Room schema snapshot present and version-matched: {version}')
print('RESULT: PASS')
