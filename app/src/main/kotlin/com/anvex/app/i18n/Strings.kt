package com.anvex.app.i18n

import androidx.compose.runtime.Composable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.ui.platform.LocalConfiguration

/**
 * Returns the Persian label for an English UI string when the app language is Persian.
 * Strings without a translation fall back to English, so new text never shows as blank.
 */
@Composable
@ReadOnlyComposable
fun tr(english: String): String {
    // The in-app language choice wins over the platform locale, which per-app locale APIs do not
    // switch reliably (the layout could flip to RTL while the text stayed English).
    val language = LocalAppLanguage.current ?: LocalConfiguration.current.locales.get(0).language
    return if (language == "fa") FA[english] ?: english else english
}

