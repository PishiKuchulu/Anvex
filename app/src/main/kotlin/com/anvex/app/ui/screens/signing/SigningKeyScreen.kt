/**
 * v4.4.6: on-device APK signing-key factory.
 *
 * Generates an RSA signing key + self-signed certificate as PKCS12 entirely on
 * the phone (the private key never leaves the device), then optionally pushes
 * the four Gradle signing secrets to a GitHub repository via the Actions
 * Secrets API (libsodium sealed box).
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SigningKeyScreen(nav: NavController, vm: SigningKeyViewModel = viewModel()) {
    val context = LocalContext.current
    val generated by vm.generated.collectAsState()
    val busy by vm.busy.collectAsState()
    val status by vm.status.collectAsState()
    val pushDone by vm.pushDone.collectAsState()

    var alias by remember { mutableStateOf("anvex") }
    var storePassword by remember { mutableStateOf("") }
    var keyPassword by remember { mutableStateOf("") }
    var validity by remember { mutableStateOf("30") }
    var owner by remember { mutableStateOf("") }
    var repo by remember { mutableStateOf("") }
    var pushStorePw by remember { mutableStateOf("") }
    var pushKeyPw by remember { mutableStateOf("") }

    // v4.4.6: SAF picker — the user chooses where the .p12 goes (the old
    // app-private path under Android/data is not browsable on modern Android).
    // rememberLauncherForActivityResult keeps the callback fresh via
    // rememberUpdatedState, so `generated` below is always current.
    val downloadLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.CreateDocument("application/x-pkcs12"),
    ) { uri ->
        if (uri == null) return@rememberLauncherForActivityResult
        val bytes = generated?.pkcs12 ?: return@rememberLauncherForActivityResult
        runCatching {
            context.contentResolver.openOutputStream(uri)?.use { it.write(bytes) }
                ?: throw IllegalStateException("Could not open the chosen file.")
            "Saved — keep a backup somewhere safe."
        }.onSuccess { vm.setStatus(it) }
            .onFailure { vm.setStatus(it.message ?: "Download failed.") }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(tr("Signing key")) },
                navigationIcon = { IconButton({ nav.popBackStack() }) { Icon(Icons.AutoMirrored.Filled.ArrowBack, "Back") } },
            )
        },
    ) { padding ->
        Column(
            Modifier.padding(padding).fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Filled.Key, null, tint = MaterialTheme.colorScheme.primary)
                        Spacer(Modifier.width(8.dp))
                        Text(tr("On-device signing key"), style = MaterialTheme.typography.titleMedium)
                    }
                    Text(
                        tr("Creates an RSA signing key and self-signed certificate as PKCS12 (.p12) right on this phone — the private key never leaves the device. Then push the four Gradle signing secrets straight to your GitHub repository."),
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }

            if (generated == null) {
                // -- Generation form --
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        Text(tr("Generate keystore"), style = MaterialTheme.typography.titleSmall)
                        OutlinedTextField(alias, { alias = it }, label = { Text(tr("Key alias")) }, singleLine = true, modifier = Modifier.fillMaxWidth())
                        OutlinedTextField(
                            storePassword, { storePassword = it },
                            label = { Text(tr("Store password")) }, singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        OutlinedTextField(
                            keyPassword, { keyPassword = it },
                            label = { Text(tr("Key password")) }, singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        OutlinedTextField(
                            validity, { v -> validity = v.filter { it.isDigit() }.take(2) },
                            label = { Text(tr("Validity (years)")) }, singleLine = true,
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Button(
                            onClick = {
                                vm.generate(
                                    alias,
                                    storePassword.toCharArray(),
                                    keyPassword.toCharArray(),
                                    validity.toIntOrNull() ?: 30,
                                )
                                storePassword = ""
                                keyPassword = ""
                            },
                            enabled = !busy && alias.isNotBlank() && storePassword.length >= 6 && keyPassword.length >= 6,
                            modifier = Modifier.fillMaxWidth(),
                        ) {
                            if (busy) CircularProgressIndicator(Modifier.size(18.dp), strokeWidth = 2.dp)
                            else Text(tr("Generate signing key"))
                        }
                    }
                }
            } else {
                val gen = generated!!
                // -- Result: fingerprint + backup warning + download --
                Card(
                    Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer),
                ) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        Text(tr("Key generated"), style = MaterialTheme.typography.titleSmall)
                        Text(tr("SHA-256 fingerprint:"), style = MaterialTheme.typography.labelMedium)
                        Text(
                            gen.fingerprint,
                            style = MaterialTheme.typography.bodySmall,
                            fontFamily = FontFamily.Monospace,
                        )
                    }
                }
                Card(
                    Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.errorContainer),
                ) {
                    Row(Modifier.padding(16.dp), verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Filled.Warning, null, tint = MaterialTheme.colorScheme.onErrorContainer)
                        Spacer(Modifier.width(8.dp))
                        Text(
                            tr("Back up the .p12 file now. If you lose the keystore, you can never update apps signed with it."),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onErrorContainer,
                        )
                    }
                }
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(
                        onClick = { downloadLauncher.launch("${gen.alias}-release.p12") },
                        modifier = Modifier.weight(1f),
                    ) {
                        Icon(Icons.Filled.Download, null)
                        Spacer(Modifier.width(6.dp))
                        Text(tr("Download .p12"))
                    }
                    OutlinedButton(onClick = { vm.clearGenerated() }, modifier = Modifier.weight(1f)) {
                        Text(tr("Discard"))
                    }
                }

                // -- Push to GitHub Secrets --
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        Text(tr("Push to GitHub Secrets"), style = MaterialTheme.typography.titleSmall)
                        Text(
                            tr("Pushes KEYSTORE_BASE64, KEYSTORE_PASSWORD, KEY_ALIAS and KEY_PASSWORD to the repository's Actions secrets (encrypted with the repo key). Needs a connected GitHub token."),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            OutlinedTextField(owner, { owner = it }, label = { Text(tr("Owner")) }, singleLine = true, modifier = Modifier.weight(1f))
                            OutlinedTextField(repo, { repo = it }, label = { Text(tr("Repository")) }, singleLine = true, modifier = Modifier.weight(1f))
                        }
                        OutlinedTextField(
                            pushStorePw, { pushStorePw = it },
                            label = { Text(tr("Store password (again)")) }, singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        OutlinedTextField(
                            pushKeyPw, { pushKeyPw = it },
                            label = { Text(tr("Key password (again)")) }, singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Button(
                            onClick = {
                                vm.pushSecrets(owner, repo, pushStorePw.toCharArray(), pushKeyPw.toCharArray())
                                pushStorePw = ""
                                pushKeyPw = ""
                            },
                            enabled = !busy && !pushDone && owner.isNotBlank() && repo.isNotBlank() &&
                                pushStorePw.length >= 6 && pushKeyPw.length >= 6,
                            modifier = Modifier.fillMaxWidth(),
                        ) {
                            if (busy) CircularProgressIndicator(Modifier.size(18.dp), strokeWidth = 2.dp)
                            else Text(if (pushDone) tr("Pushed ✓") else tr("Push 4 secrets"))
                        }
                    }
                }
            }

            status?.let {
                Text(
                    it,
                    color = if (it.contains("fail", true) || it.contains("denied", true) || it.contains("invalid", true) || it.contains("could not", true))
                        MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.primary,
                )
            }
        }
    }
}
